import { test, expect } from '@playwright/test'

test('受信箱からメール詳細を開ける', async ({ page }) => {
  const pageErrors: string[] = []
  page.on('pageerror', (error) => pageErrors.push(error.message))

  await page.goto('/')
  await expect(page.getByText('キャンパスメール')).toBeVisible()
  await expect(page.getByText('重要なメール')).toBeVisible()
  await expect(page.getByText('【都立大生限定】大手IT企業合同オンライン説明会のご案内')).toBeVisible()
  await expect(page.getByText('冬期エンジニアインターンシップ選考エントリー受付開始')).not.toBeVisible()
  await expect(page.getByText('レポートはkibacoでPDF提出必須。文字数は2,000字以上、サンプルコードの添付が必要です。')).not.toBeVisible()
  await expect(page.locator('article.email-card')).toHaveCount(3)
  await page.getByRole('button', { name: '検索' }).click()
  await page.getByPlaceholder('メールを検索').fill('図書館')
  await expect(page.locator('article.email-card')).toHaveCount(0)
  await page.getByRole('button', { name: /すべて/ }).click()
  await expect(page.locator('article.email-card')).toHaveCount(1)
  await expect(page.getByText('電子ジャーナルサービス停止のお知らせ')).toBeVisible()
  await page.getByRole('button', { name: '検索を閉じる' }).click()
  await page.getByRole('button', { name: /すべて/ }).click()
  await expect(page.getByText('すべてのメール')).toBeVisible()
  await page.getByRole('button', { name: /🔥 重要/ }).click()
  await expect(page.getByText('重要なメール')).toBeVisible()
  await expect(page.getByText('冬期エンジニアインターンシップ選考エントリー受付開始')).not.toBeVisible()
  await page.getByRole('button', { name: /すべて/ }).click()
  await expect(page.getByText('すべてのメール')).toBeVisible()
  await page.getByRole('button', { name: /興味/ }).click()
  await expect(page.getByText('興味メール')).toBeVisible()
  await expect(page.getByText('冬期エンジニアインターンシップ選考エントリー受付開始')).toBeVisible()
  await expect(page.getByText('キャンパス内駐輪場点検のお知らせ（定期点検）')).not.toBeVisible()
  await page.getByRole('button', { name: 'マイ条件' }).click()
  await page.getByRole('button', { name: '変更する' }).click()
  await page.getByLabel('所属学部').fill('都市環境学部')
  await page.getByLabel('学年').fill('第4学年')
  await page.getByRole('button', { name: 'プロフィールを保存' }).click()
  await expect(page.getByText('都市環境学部')).toBeVisible()
  await expect(page.getByText('第4学年')).toBeVisible()
  await page.getByLabel('興味のある分野を追加').fill('音楽イベント')
  await page.locator('.custom-interest-form').getByRole('button', { name: '＋ 追加' }).click()
  await expect(page.getByRole('button', { name: /音楽イベント/ })).toBeVisible()
  await page.getByRole('button', { name: '就職活動・インターン' }).click()
  await page.getByRole('button', { name: '研究室・卒論' }).click()
  await page.getByRole('button', { name: /この設定でメールを整理する/ }).click()
  await expect(page.getByRole('status')).toHaveText('興味のある分野を保存しました。興味メールに反映されています。')
  await page.getByRole('button', { name: '受信箱' }).click()
  await page.getByRole('button', { name: /興味/ }).click()
  await expect(page.getByText('第7回レポート課題提出について（締切: 11/15）')).toBeVisible()
  await expect(page.getByText('大手IT企業合同オンライン説明会のご案内')).not.toBeVisible()
  await page.getByRole('button', { name: /すべて/ }).click()
  await expect(page.getByText('すべてのメール')).toBeVisible()
  await page.getByText('【重要・課題】第7回レポート課題提出について（締切: 11/15）').click()
  await expect(page.getByText('AI要約サマリー')).toBeVisible()
  await expect(page.getByText('提出締切')).toBeVisible()
  await expect(page.getByText('第7回_課題指示書.pdf')).toBeVisible()

  await page.getByRole('button', { name: '‹' }).click()
  await expect(page.getByText('重要なメール')).toBeVisible()
  const hasHorizontalOverflow = await page.evaluate(
    () => document.documentElement.scrollWidth > window.innerWidth,
  )
  expect(hasHorizontalOverflow).toBe(false)
  expect(pageErrors).toEqual([])
})
